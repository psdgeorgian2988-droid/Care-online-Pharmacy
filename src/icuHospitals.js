const PREFIX_ORIGIN = {
  110: [28.6139, 77.209],
  121: [28.4089, 77.3178],
  122: [28.4595, 77.0266],
  201: [28.6692, 77.4538],
  203: [28.4743, 77.504],
};

export function haversineKm(lat1, lng1, lat2, lng2) {
  const toRad = (value) => (value * Math.PI) / 180;
  const dLat = toRad(lat2 - lat1);
  const dLng = toRad(lng2 - lng1);
  const a =
    Math.sin(dLat / 2) ** 2 +
    Math.cos(toRad(lat1)) * Math.cos(toRad(lat2)) * Math.sin(dLng / 2) ** 2;
  return 6371 * 2 * Math.asin(Math.min(1, Math.sqrt(a)));
}

export function originForPickup({ lat, lng, pin } = {}) {
  const latitude = Number(lat);
  const longitude = Number(lng);
  if (Number.isFinite(latitude) && Number.isFinite(longitude)) {
    if (latitude !== 0 || longitude !== 0) {
      return { lat: latitude, lng: longitude };
    }
  }
  const code = String(pin || "").replace(/\D/g, "");
  const prefix = PREFIX_ORIGIN[code.slice(0, 3)];
  if (prefix) return { lat: prefix[0], lng: prefix[1] };
  return null;
}

export function hospitalDestination(hospital) {
  if (!hospital) {
    return {
      destinationId: "",
      destinationName: "",
      destinationAddress: "",
      destinationPin: "",
      destinationPhone: "",
      destinationKm: "",
      destinationFacilities: "",
    };
  }
  return {
    destinationId: hospital.id,
    destinationName: hospital.name,
    destinationAddress: hospital.address,
    destinationPin: hospital.pin,
    destinationPhone: hospital.phone || "",
    destinationKm:
      hospital.distanceKm != null && hospital.distanceKm !== ""
        ? hospital.distanceKm
        : "",
    destinationFacilities: (hospital.facilities || ["ICU", "Ventilator"]).join(
      ", "
    ),
  };
}

export function nearestIcuHospitals({ lat, lng, pin, limit = 3 } = {}) {
  const origin = originForPickup({ lat, lng, pin });
  const ranked = ICU_VENTILATOR_HOSPITALS.map((row) => {
    const km = origin
      ? Math.round(haversineKm(origin.lat, origin.lng, row.lat, row.lng) * 10) /
        10
      : null;
    return {
      ...row,
      distanceKm: km,
      mapsUrl: `https://www.google.com/maps/search/?api=1&query=${encodeURIComponent(
        `${row.lat},${row.lng}`
      )}`,
    };
  }).sort((a, b) => {
    if (a.distanceKm == null && b.distanceKm == null) {
      return a.name.localeCompare(b.name);
    }
    if (a.distanceKm == null) return 1;
    if (b.distanceKm == null) return -1;
    return a.distanceKm - b.distanceKm;
  });
  const count = Math.max(1, Number(limit) || 3);
  return ranked.slice(0, count);
}

export function formatHospitalDistance(km) {
  if (km == null || km === "") return "";
  const n = Number(km);
  if (!Number.isFinite(n)) return "";
  return `${n.toLocaleString("en-IN", { maximumFractionDigits: 1 })} km`;
}
